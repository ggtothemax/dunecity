#!/usr/bin/env node
/**
 * Materializes the committed p2pkit IIFE bundle for the browser build
 * (platform/web/dist/p2pkit.iife.js) from the installed p2pkit dependency.
 *
 * The bytes come from the package's own build: `npm install` in
 * platform/web installs the exact revision pinned in platform/web/package.json
 * and runs the package's `prepare` script (tsup build + build:iife), which
 * produces node_modules/p2pkit/dist/p2pkit.iife.js. This script copies those
 * exact bytes (plus a provenance header) so the committed artifact, the
 * browser runtime and the Node unit tests all use the same bytes from the
 * same pinned revision — no Dune-owned bundler, no second copy of SDK source.
 *
 * If the installed package is missing, run:  npm install  (in platform/web).
 * Set P2PKIT_SKIP_BUILD=1 (or legacy P2PKIT_SKIP_INSTALL=1) to make a missing
 * dependency a hard error instead of hinting at regeneration (offline runs).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = path.join(ROOT, 'platform/web/dist/p2pkit.iife.js');
const PKG_DIR = path.join(ROOT, 'platform/web/node_modules/p2pkit');
const PKG_DIST = path.join(PKG_DIR, 'dist/p2pkit.iife.js');
const MANIFEST = path.join(ROOT, 'platform/web/package.json');

const skip = process.env.P2PKIT_SKIP_BUILD === '1' || process.env.P2PKIT_SKIP_INSTALL === '1';

function fail(msg) {
  console.error(`ERROR: ${msg}${skip ? ' (P2PKIT_SKIP_BUILD=1)' : ''}`);
  process.exit(1);
}

if (!fs.existsSync(path.join(PKG_DIR, 'package.json'))) {
  fail(`p2pkit dependency not installed at ${PKG_DIR}. Run: npm install  (in platform/web) to install the revision pinned in platform/web/package.json`);
}
if (!fs.existsSync(PKG_DIST)) {
  fail(`${PKG_DIST} is missing. The package's own prepare script (build + build:iife) produces it during npm install; re-run: npm install  (in platform/web)`);
}

const pin = JSON.parse(fs.readFileSync(MANIFEST, 'utf8')).dependencies?.p2pkit;
const version = JSON.parse(fs.readFileSync(path.join(PKG_DIR, 'package.json'), 'utf8')).version;
const body = fs.readFileSync(PKG_DIST, 'utf8');
// Deterministic header (no timestamps): reruns on the same pin produce
// byte-identical output, so the committed artifact stays diffable.
const header = [
  '// Generated by tools/web/build-p2pkit-iife.mjs — do not edit.',
  `// Copied verbatim from the installed p2pkit dependency (${pin}, package version ${version}),`,
  '// which builds this file itself (prepare -> npm run build:iife) during npm install.',
  '// Exposes globalThis.P2PKIT_IIFE for the Emscripten browser runtime.',
  '',
].join('\n');

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, header + body);
console.log(`OK: wrote ${OUT} (${fs.statSync(OUT).size} bytes) from ${PKG_DIST} (${pin})`);
